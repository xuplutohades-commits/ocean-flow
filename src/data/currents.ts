/** 某洋流在给定季节下的路径 */
export function pathOf(c: OceanCurrent, season: 'summer' | 'winter'): [number, number][] {
  if (c.seasonal && season === 'summer' && c.summerPath) return c.summerPath;
  if (c.seasonal && season === 'winter' && c.winterPath) return c.winterPath;
  return c.path;
}

/** 标签锚点：取路径中段稍偏的点 */
export function labelPoint(c: OceanCurrent, season: 'summer' | 'winter'): [number, number] {
  const p = pathOf(c, season);
  return p[Math.floor(p.length * 0.5)];
}

export const WARM_COLOR = '#ff9d5c';


/** 考虑季节的洋流性质：索马里沿岸流冬季转暖（上升流停止） */
export function seasonalType(c: OceanCurrent, season: 'summer' | 'winter'): 'warm' | 'cold' {
  if (c.id === 'somaliSummer' && season === 'winter') return 'warm';
  return c.type;
}
